"use client"

import { useTheme } from "next-themes"
import { Toaster as Sonner, type ToasterProps } from "sonner"
import { CircleCheckIcon, InfoIcon, TriangleAlertIcon, OctagonXIcon, Loader2Icon } from "lucide-react"

/**
 * Themed Toaster. Colors (primary brand background, semantic warning/error)
 * and the close button styling live in globals.css under "Sonner toasts" —
 * stylesheet !important beats Sonner's inline styles. Icons inherit the
 * toast's text color.
 */
const Toaster = ({ ...props }: ToasterProps) => {
  const { theme = "system" } = useTheme()

  return (
    <Sonner
      theme={theme as ToasterProps["theme"]}
      className="toaster group"
      icons={{
        success: <CircleCheckIcon className="size-4" />,
        info: <InfoIcon className="size-4" />,
        warning: <TriangleAlertIcon className="size-4" />,
        error: <OctagonXIcon className="size-4" />,
        loading: <Loader2Icon className="size-4 animate-spin" />,
      }}
      /* Real close button on every toast — clickable, no swiping needed. */
      closeButton
      {...props}
    />
  )
}

export { Toaster }
